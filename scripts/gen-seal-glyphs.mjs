// Extracts the outlines of every seal character (lib/design/seals.ts) from
// Noto Serif SC Black (SIL OFL 1.1) into lib/design/seal-glyphs.generated.ts.
//
// Not part of gen-all: the source font is 15 MB and only matters when a seal
// character changes. It is downloaded once into .cache/fonts/ (gitignored) and
// verified by SHA-256; the generated module is committed.
//
//   pnpm gen-seal-glyphs
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import opentype from "opentype.js";
import { sealCharacters } from "../lib/design/seals.ts";

const FONT_URL =
  "https://cdn.jsdelivr.net/npm/@expo-google-fonts/noto-serif-sc@0.4.3/900Black/NotoSerifSC_900Black.ttf";
const FONT_SHA256 = "092e71a70c744be3cc33999eb4edcb10fbe95c1b4cff6c2d7f04d6ff15d031e2";
const CACHE = path.join(process.cwd(), ".cache/fonts/NotoSerifSC-900.ttf");
const OUT = path.join(process.cwd(), "lib/design/seal-glyphs.generated.ts");

/** Glyphs are fitted into this share of the 100-unit seal face. */
const GLYPH_EXTENT = 70;

async function loadFont() {
  if (!existsSync(CACHE)) {
    console.log(`Downloading ${FONT_URL}`);
    const response = await fetch(FONT_URL);
    if (!response.ok) throw new Error(`Font download failed: ${response.status}`);
    mkdirSync(path.dirname(CACHE), { recursive: true });
    writeFileSync(CACHE, Buffer.from(await response.arrayBuffer()));
  }
  const buffer = readFileSync(CACHE);
  const digest = createHash("sha256").update(buffer).digest("hex");
  if (process.env.SEAL_FONT_SHA256 !== "skip" && digest !== FONT_SHA256) {
    throw new Error(`Unexpected font checksum ${digest}; delete ${CACHE} and retry.`);
  }
  return opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.length));
}

// Whole units: at 100 units per face that is sub-pixel up to a 100 px seal, and
// it halves the markup every page that shows a seal carries in HTML and RSC.
const round = (value) => Math.round(value);

function fittedPath(font, char) {
  const glyph = font.charToGlyph(char);
  if (!glyph || glyph.index === 0) throw new Error(`Font has no glyph for ${char}`);
  const raw = glyph.getPath(0, 0, 100);
  const box = raw.getBoundingBox();
  const scale = GLYPH_EXTENT / Math.max(box.x2 - box.x1, box.y2 - box.y1);
  const dx = 50 - ((box.x1 + box.x2) / 2) * scale;
  const dy = 50 - ((box.y1 + box.y2) / 2) * scale;
  const X = (x) => round(x * scale + dx);
  const Y = (y) => round(y * scale + dy);
  return raw.commands
    .map((c) => {
      switch (c.type) {
        case "M":
        case "L":
          return `${c.type}${X(c.x)} ${Y(c.y)}`;
        case "Q":
          return `Q${X(c.x1)} ${Y(c.y1)} ${X(c.x)} ${Y(c.y)}`;
        case "C":
          return `C${X(c.x1)} ${Y(c.y1)} ${X(c.x2)} ${Y(c.y2)} ${X(c.x)} ${Y(c.y)}`;
        default:
          return "Z";
      }
    })
    .join("")
    .replace(/ -/g, "-");
}

const font = await loadFont();
const entries = sealCharacters()
  .sort()
  .map((char) => `  "${char}": "${fittedPath(font, char)}",`);

writeFileSync(
  OUT,
  [
    "// Generated by `pnpm gen-seal-glyphs` from Noto Serif SC Black (SIL OFL 1.1).",
    "// Do not edit by hand. Paths are fitted into a 100 × 100 seal face.",
    "export const SEAL_GLYPHS: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n")
);
console.log(`Wrote ${entries.length} seal glyphs → ${path.relative(process.cwd(), OUT)}`);
